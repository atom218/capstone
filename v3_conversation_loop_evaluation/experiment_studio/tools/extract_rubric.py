#!/usr/bin/env python3
"""Convert LLM-judge-rubric-and-instructions.docx into js/judge_rubric.js.

The judges receive this text verbatim as their instructions, so rerun this
script whenever the document changes, then rebuild the Studio:

    python3 tools/extract_rubric.py && python3 build_studio.py
"""

import hashlib
import html
import json
import re
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
DOCX = HERE.parent / "LLM-judge-rubric-and-instructions.docx"
OUT_JS = HERE / "js" / "judge_rubric.js"
OUT_MD = HERE / "judge_rubric.md"


def run_text(xml):
    parts = re.findall(r"<w:t(?:\s[^>]*)?>(.*?)</w:t>|(<w:tab/>)|(<w:br/>)", xml, flags=re.S)
    out = []
    for text, tab, br in parts:
        if tab:
            out.append("\t")
        elif br:
            out.append("\n")
        else:
            out.append(html.unescape(text))
    return "".join(out).strip()


def paragraph(xml):
    style = re.search(r'<w:pStyle w:val="([^"]+)"', xml)
    return (style.group(1) if style else ""), run_text(xml)


def table(xml):
    rows = []
    for tr in re.findall(r"<w:tr[ >].*?</w:tr>", xml, flags=re.S):
        cells = []
        for tc in re.findall(r"<w:tc[ >].*?</w:tc>", tr, flags=re.S):
            paras = [paragraph(p)[1] for p in re.findall(r"<w:p[ >].*?</w:p>", tc, flags=re.S)]
            cells.append(" ".join(p for p in paras if p))
        rows.append(cells)
    if not rows:
        return ""
    header, body = rows[0], rows[1:]
    lines = []
    for row in body:
        pairs = [f"{h}: {c}" for h, c in zip(header, row) if c]
        lines.append("- " + " | ".join(pairs))
    return "\n".join(lines)


def convert():
    xml = zipfile.ZipFile(DOCX).read("word/document.xml").decode("utf-8")
    body = re.search(r"<w:body>(.*)</w:body>", xml, flags=re.S).group(1)
    blocks = re.findall(r"<w:tbl>.*?</w:tbl>|<w:p[ >].*?</w:p>", body, flags=re.S)
    lines, number = [], 0
    for block in blocks:
        if block.startswith("<w:tbl>"):
            lines.append(table(block))
            continue
        style, text = paragraph(block)
        if not text:
            continue
        if style == "Title":
            lines.append(f"# {text}")
        elif style.startswith("Heading"):
            number = 0
            lines.append(f"\n## {text}")
        elif style.startswith("ListNumber"):
            number += 1
            lines.append(f"{number}. {text}")
        elif style.startswith("ListBullet"):
            lines.append(f"- {text}")
        else:
            lines.append(text)
    return "\n".join(lines).strip() + "\n"


def main():
    text = convert()
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]
    OUT_MD.write_text(text, encoding="utf-8")
    OUT_JS.write_text(
        "/* Generated by tools/extract_rubric.py from LLM-judge-rubric-and-instructions.docx. Do not edit by hand. */\n"
        '"use strict";\n'
        f"const JUDGE_RUBRIC_TEXT = {json.dumps(text, ensure_ascii=False)};\n"
        f'const JUDGE_RUBRIC_SHA = "{digest}";\n',
        encoding="utf-8",
    )
    print(f"Wrote {OUT_JS.name} and {OUT_MD.name} ({len(text)} chars, sha {digest})")


if __name__ == "__main__":
    main()
